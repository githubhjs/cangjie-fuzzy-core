#!/usr/bin/env python3
"""Build the installable two-stream fuzzy schema pair from the plain cangjie3_fluency schema.

  cangjie3_fuzzy.schema.yaml        exact stream (unchanged translator, quality +100) + fuzzy stream (quality -100)
  cangjie3_fuzzy_prism.schema.yaml  helper schema: same dictionary, speller algebra with the one-substitution marker rules;
                                    it only exists to build the fuzzy prism (listed in `dependencies` of the main schema)

usage: package_fuzzy.py --map neighbors_pc.json --out DIR [--src cangjie3_fluency.schema.yaml] [--profile-name pc]
The generator rules come from gen_fuzzy.py (default: tolerance 1, spellings of length 2..5, one stage).
"""
import argparse, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import json
import gen_fuzzy

ap = argparse.ArgumentParser()
ap.add_argument("--map", required=True)
ap.add_argument("--out", required=True)
ap.add_argument("--src", default="/home/hjs/projects/cangjie-fluency/weasel/cangjie3_fluency.schema.yaml")
ap.add_argument("--profile-name", default="pc")
ap.add_argument("--tolerance", type=int, default=1)
ap.add_argument("--quality", type=int, default=100)
a = ap.parse_args()

nb = json.load(open(a.map))
rules = gen_fuzzy.rules(nb, a.tolerance, 2, 5, 1, False)
src = open(a.src, encoding="utf-8").read()
os.makedirs(a.out, exist_ok=True)

# ---- helper schema: identical to the plain schema except id, prism and the algebra rules
helper = src.replace("schema_id: cangjie3_fluency", "schema_id: cangjie3_fuzzy_prism")
helper = helper.replace("prism: cangjie3_fluency", "prism: cangjie3_fuzzy_prism")
marker = "    - 'xform/^(\\w)$/$1 /'"
assert marker in helper
helper = helper.replace(marker, "".join("    - '%s'\n" % r for r in rules) + marker)
helper = re.sub(r"^  name: .*$", "  name: 倉頡三代容錯（內部：容錯索引，請勿選用）", helper, count=1, flags=re.M)
open(os.path.join(a.out, "cangjie3_fuzzy_prism.schema.yaml"), "w", encoding="utf-8").write(helper)

# ---- main schema: add the second translator and the fuzzy namespace
main = src.replace("schema_id: cangjie3_fluency", "schema_id: cangjie3_fuzzy")
main = re.sub(r"^  name: .*$", "  name: 倉頡三代整句（鄰鍵容錯，%s 鍵盤）" % a.profile_name, main, count=1, flags=re.M)
main = main.replace("  dependencies:\n    - luna_quanpin", "  dependencies:\n    - luna_quanpin\n    - cangjie3_fuzzy_prism", 1)
assert "    - script_translator\n" in main
main = main.replace("    - script_translator\n", "    - script_translator\n    - script_translator@fuzzy\n", 1)
# exact stream keeps its prism and gets a high quality so it is always listed before the fuzzy candidates
main = main.replace("translator:\n  dictionary: cangjie3_fluency\n  prism: cangjie3_fluency\n",
                    "translator:\n  dictionary: cangjie3_fluency\n  prism: cangjie3_fluency\n  initial_quality: %d\n" % a.quality, 1)
# fuzzy namespace = the translator block with another prism and a negative quality
m = re.search(r"^translator:\n(?:  .*\n|\n)+?(?=^\S)", main, flags=re.M)
assert m, "translator block not found"
block = m.group(0)
fz = block.replace("translator:\n", "fuzzy:\n", 1)
fz = fz.replace("prism: cangjie3_fluency", "prism: cangjie3_fuzzy_prism", 1)
fz = fz.replace("initial_quality: %d" % a.quality, "initial_quality: %d" % (-a.quality), 1)
main = main.replace(block, block + fz.rstrip("\n") + "\n\n", 1)
header = ("# cangjie3_fuzzy: adjacent-key typo tolerance (%s keyboard), generated by package_fuzzy.py from cangjie3_fluency.\n"
          "# Two streams: the exact translator is unchanged and always first; the fuzzy translator offers candidates reachable by ONE\n"
          "# adjacent-key substitution in a spelling of 2 to 5 letters, listed after the exact ones.\n" % a.profile_name)
open(os.path.join(a.out, "cangjie3_fuzzy.schema.yaml"), "w", encoding="utf-8").write(header + main)
print("rules:", len(rules), "| wrote", a.out)
